-- ==========================================================================
-- Chess-Book premium backend: tables, security and payment fulfilment
-- Paste this WHOLE file into Supabase > SQL Editor > New query > Run.
-- It is safe to run more than once. Prices are in RUPEES (Rs 2 = 2).
-- Orders store the amount in PAISE (Rs 2 = 200), which is what Razorpay uses.
-- ==========================================================================

-- 1. Plans -----------------------------------------------------------------
create table if not exists public.plans (
  id             text primary key,
  name           text not null,
  price          integer not null check (price >= 0),   -- rupees
  currency       text not null default 'INR',
  duration_hours integer,
  is_lifetime    boolean not null default false,
  is_active      boolean not null default true,
  created_at     timestamptz not null default now()
);

insert into public.plans (id, name, price, currency, duration_hours, is_lifetime) values
  ('1h',       '1 Hour Premium',   2, 'INR', 1,    false),
  ('6h',       '6 Hours Premium',  5, 'INR', 6,    false),
  ('12h',      '12 Hours Premium', 8, 'INR', 12,   false),
  ('24h',      '24 Hours Premium', 10, 'INR', 24,  false),
  ('lifetime', 'Lifetime Premium', 50, 'INR', null, true)
on conflict (id) do update set
  name = excluded.name, price = excluded.price, currency = excluded.currency,
  duration_hours = excluded.duration_hours, is_lifetime = excluded.is_lifetime;

alter table public.plans enable row level security;
drop policy if exists "Anyone can read active plans" on public.plans;
create policy "Anyone can read active plans" on public.plans
  for select to anon, authenticated using (is_active = true);

-- 2. Orders ----------------------------------------------------------------
create table if not exists public.payment_orders (
  id                  bigint generated by default as identity primary key,
  user_id             uuid not null references auth.users(id),
  plan_id             text not null references public.plans(id),
  amount              integer not null,                 -- paise
  currency            text not null default 'INR',
  razorpay_order_id   text unique not null,
  razorpay_payment_id text unique,
  status              text not null default 'created' check (status in ('created','paid','failed')),
  created_at          timestamptz not null default now()
);
alter table public.payment_orders add column if not exists razorpay_payment_id text unique;
alter table public.payment_orders add column if not exists paid_at timestamptz;

alter table public.payment_orders enable row level security;
drop policy if exists "Read own orders" on public.payment_orders;
create policy "Read own orders" on public.payment_orders
  for select to authenticated using (user_id = auth.uid());

-- 3. Entitlements (who has Premium, and until when) ------------------------
create table if not exists public.entitlements (
  user_id     uuid primary key references auth.users(id),
  is_lifetime boolean not null default false,
  expires_at  timestamptz,
  updated_at  timestamptz not null default now()
);

alter table public.entitlements enable row level security;
drop policy if exists "Read own entitlement" on public.entitlements;
create policy "Read own entitlement" on public.entitlements
  for select to authenticated using (user_id = auth.uid());

-- The app must never be able to write payment or entitlement rows.
revoke insert, update, delete on public.payment_orders from anon, authenticated;
revoke insert, update, delete on public.entitlements   from anon, authenticated;
revoke insert, update, delete on public.plans          from anon, authenticated;

-- 4. Fulfilment: ONE atomic, repeatable step -------------------------------
-- Called by the server functions after a payment is proven genuine.
-- Calling it twice for the same order is harmless (returns 'already_paid').
-- Marking the order paid and granting access happen in the same transaction,
-- so a crash can never leave "paid but no Premium".
create or replace function public.fulfil_payment(
  p_razorpay_order_id   text,
  p_razorpay_payment_id text,
  p_amount_paise        integer
) returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  o public.payment_orders;
  pl public.plans;
  e public.entitlements;
begin
  select * into o from public.payment_orders
   where razorpay_order_id = p_razorpay_order_id for update;
  if not found then return 'order_not_found'; end if;
  if o.status = 'paid' then return 'already_paid'; end if;
  if o.amount is distinct from p_amount_paise then return 'amount_mismatch'; end if;

  select * into pl from public.plans where id = o.plan_id;
  if not found then return 'plan_not_found'; end if;

  update public.payment_orders
     set status = 'paid', razorpay_payment_id = p_razorpay_payment_id, paid_at = now()
   where id = o.id;

  insert into public.entitlements (user_id) values (o.user_id)
    on conflict (user_id) do nothing;
  select * into e from public.entitlements where user_id = o.user_id for update;

  if pl.is_lifetime then
    update public.entitlements
       set is_lifetime = true, expires_at = null, updated_at = now()
     where user_id = o.user_id;
  elsif not e.is_lifetime then
    -- Extend from the current expiry if still active, so buying again never wastes paid time.
    update public.entitlements
       set expires_at = greatest(coalesce(e.expires_at, now()), now()) + make_interval(hours => pl.duration_hours),
           updated_at = now()
     where user_id = o.user_id;
  end if;

  return 'fulfilled';
end;
$$;

-- 5. Status shown in the app (uses SERVER time, so phone clock tricks do nothing)
create or replace function public.entitlement_status(p_user_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'premium',     coalesce(e.is_lifetime or (e.expires_at is not null and e.expires_at > now()), false),
    'lifetime',    coalesce(e.is_lifetime, false),
    'expires_at',  case when coalesce(e.is_lifetime, false) then null else e.expires_at end,
    'server_time', now()
  )
  from (select 1) s
  left join public.entitlements e on e.user_id = p_user_id;
$$;

-- Only the server functions (service role) may run these two.
revoke all on function public.fulfil_payment(text, text, integer) from public, anon, authenticated;
revoke all on function public.entitlement_status(uuid)            from public, anon, authenticated;
grant execute on function public.fulfil_payment(text, text, integer) to service_role;
grant execute on function public.entitlement_status(uuid)            to service_role;

